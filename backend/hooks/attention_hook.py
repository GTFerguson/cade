"""The attention hook: tells CADE when the agent is waiting on the user.

Installed as ``~/.cade/hooks/attention.py`` and wired to Claude Code's
Notification, Stop and UserPromptSubmit hooks, and to Codex's ``notify``.
It is a standalone stdlib-only script, like the view hook, because it runs
inside the agent's process environment, not CADE's.
"""

from __future__ import annotations

ATTENTION_SCRIPT = '''\
#!/usr/bin/env python3
"""CADE attention hook — reports agent state (waiting / done / working).

Generated by CADE at startup. Do not edit manually.

Claude Code pipes the hook JSON on stdin. Codex passes it as argv[1] when
run via ``notify``. Both end up as one POST to CADE's attention endpoint.
"""

import json
import os
import sys
import time
import urllib.request

DEFAULT_PORT = 3001
cade_dir = os.path.join(os.path.expanduser("~"), ".cade")


def log(msg):
    try:
        with open(os.path.join(cade_dir, "hook.log"), "a") as f:
            f.write("[%s] attention: %s\\n" % (time.strftime("%Y-%m-%d %H:%M:%S"), msg))
    except Exception:
        pass


def read_setting(name, default):
    try:
        with open(os.path.join(cade_dir, name)) as f:
            value = f.read().strip()
            return value or default
    except Exception:
        return default


def main():
    if len(sys.argv) > 1 and sys.argv[1] not in ("-", ""):
        raw = sys.argv[1]
    else:
        raw = sys.stdin.read()
    try:
        data = json.loads(raw) if raw.strip() else {}
    except Exception as e:
        log("bad JSON: %s" % e)
        return

    event = data.get("hook_event_name") or data.get("type") or ""
    payload = {
        "session_id": os.environ.get("CADE_SESSION_ID") or None,
        "cwd": data.get("cwd") or os.getcwd(),
        "event": event,
        "notification_type": data.get("notification_type"),
        "message": data.get("message") or data.get("last-assistant-message"),
    }

    host = read_setting("host", "localhost")
    port = int(read_setting("port", str(DEFAULT_PORT)))
    url = "http://%s:%d/api/sessions/attention" % (host, port)
    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=3) as resp:
            log("%s -> %d" % (event, resp.status))
    except Exception as e:
        log("%s failed: %s" % (event, e))


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        log("unhandled: %s" % e)
    sys.exit(0)
'''

SCRIPT_FILENAME = "attention.py"


def build_attention_command() -> str:
    return "python3 ~/.cade/hooks/attention.py"


def build_attention_hook_config() -> dict:
    """settings.json entry for the event-level hooks (no tool matcher)."""
    return {
        "hooks": [
            {
                "type": "command",
                "command": build_attention_command(),
            }
        ],
    }
